-- Public submission is through this function only; students do not get direct table insert access.
create or replace function public.submit_borrow_request(
  p_student_name text, p_class_name text, p_purpose text,
  p_borrow_date date, p_expected_return_date date, p_items jsonb
) returns text language plpgsql security definer set search_path=public
as $$
declare v_request_id uuid; v_code text; v_class_category public.equipment_category;
        v_item jsonb; v_equipment public.equipment%rowtype; v_qty integer;
begin
  if length(trim(coalesce(p_student_name,''))) < 2 or length(trim(p_student_name)) > 100 then
    raise exception 'Nama harus terdiri dari 2-100 karakter';
  end if;
  if p_borrow_date < current_date or p_expected_return_date < p_borrow_date then
    raise exception 'Tanggal peminjaman/pengembalian tidak valid';
  end if;
  if jsonb_typeof(p_items) <> 'array' or jsonb_array_length(p_items) < 1 or jsonb_array_length(p_items) > 20 then
    raise exception 'Pilih antara 1 sampai 20 jenis alat';
  end if;
  select category into v_class_category from public.school_classes where name=p_class_name;
  if v_class_category is null then raise exception 'Kelas tidak terdaftar'; end if;
  insert into public.borrow_requests(student_name,class_name,purpose,borrow_date,expected_return_date)
  values(trim(p_student_name),p_class_name,nullif(trim(coalesce(p_purpose,'')),''),p_borrow_date,p_expected_return_date)
  returning id,request_code into v_request_id,v_code;
  for v_item in select value from jsonb_array_elements(p_items) loop
    v_qty := (v_item->>'quantity')::integer;
    if v_qty < 1 then raise exception 'Jumlah alat tidak valid'; end if;
    select * into v_equipment from public.equipment where id=(v_item->>'equipment_id')::uuid and is_active for share;
    if not found or v_equipment.category <> v_class_category then raise exception 'Alat tidak sesuai jurusan atau tidak tersedia'; end if;
    if v_qty > v_equipment.total_stock then raise exception 'Jumlah melebihi stok total untuk %',v_equipment.name; end if;
    insert into public.borrow_request_items(request_id,equipment_id,quantity) values(v_request_id,v_equipment.id,v_qty);
  end loop;
  return v_code;
end $$;

create or replace function public.approve_borrow_request(p_request_id uuid)
returns void language plpgsql security definer set search_path=public
as $$
declare r record; v_conflict integer;
begin
  if not public.is_admin() then raise exception 'Akses admin diperlukan'; end if;
  perform 1 from public.borrow_requests where id=p_request_id and status='pending' for update;
  if not found then raise exception 'Permohonan tidak ditemukan atau bukan berstatus menunggu'; end if;
  for r in select i.equipment_id,i.quantity,e.name from public.borrow_request_items i join public.equipment e on e.id=i.equipment_id where i.request_id=p_request_id order by i.equipment_id loop
    perform 1 from public.equipment where id=r.equipment_id for update;
    select coalesce(sum(i.quantity),0) into v_conflict
    from public.borrow_request_items i join public.borrow_requests b on b.id=i.request_id
    where i.equipment_id=r.equipment_id and b.status in ('approved','borrowed')
      and daterange(b.borrow_date,b.expected_return_date,'[]') &&
          (select daterange(borrow_date,expected_return_date,'[]') from public.borrow_requests where id=p_request_id);
    if v_conflict + r.quantity > (select total_stock from public.equipment where id=r.equipment_id) then
      raise exception 'Stok % tidak cukup pada rentang tanggal tersebut',r.name;
    end if;
  end loop;
  update public.borrow_requests set status='approved' where id=p_request_id;
end $$;

create or replace function public.reject_borrow_request(p_request_id uuid)
returns void language plpgsql security definer set search_path=public
as $$ begin
  if not public.is_admin() then raise exception 'Akses admin diperlukan'; end if;
  update public.borrow_requests set status='rejected' where id=p_request_id and status='pending';
  if not found then raise exception 'Permohonan tidak ditemukan atau bukan berstatus menunggu'; end if;
end $$;

create or replace function public.mark_borrowed(p_request_id uuid)
returns void language plpgsql security definer set search_path=public
as $$
declare r record;
begin
  if not public.is_admin() then raise exception 'Akses admin diperlukan'; end if;
  update public.borrow_requests set status='borrowed' where id=p_request_id and status='approved';
  if not found then raise exception 'Permohonan harus disetujui terlebih dahulu'; end if;
  for r in select equipment_id,quantity from public.borrow_request_items where request_id=p_request_id loop
    update public.equipment set available_stock=available_stock-r.quantity where id=r.equipment_id and available_stock>=r.quantity;
    if not found then raise exception 'Stok fisik tersedia tidak mencukupi'; end if;
    insert into public.inventory_movements(equipment_id,request_id,movement_type,quantity,actor)
    values(r.equipment_id,p_request_id,'borrow',r.quantity,auth.uid());
  end loop;
end $$;

create or replace function public.confirm_return(p_request_id uuid)
returns void language plpgsql security definer set search_path=public
as $$
declare r record;
begin
  if not public.is_admin() then raise exception 'Akses admin diperlukan'; end if;
  update public.borrow_requests set status='returned',actual_return_date=current_date where id=p_request_id and status='borrowed';
  if not found then raise exception 'Permohonan belum berstatus sudah diambil'; end if;
  for r in select equipment_id,quantity from public.borrow_request_items where request_id=p_request_id loop
    update public.equipment set available_stock=least(total_stock,available_stock+r.quantity) where id=r.equipment_id;
    insert into public.inventory_movements(equipment_id,request_id,movement_type,quantity,actor)
    values(r.equipment_id,p_request_id,'return',r.quantity,auth.uid());
  end loop;
end $$;

