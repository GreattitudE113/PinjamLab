create table if not exists public.equipment (
  id uuid primary key default gen_random_uuid(),
  name text not null,
  category public.equipment_category not null,
  total_stock integer not null default 0 check(total_stock >= 0),
  available_stock integer not null default 0 check(available_stock >= 0),
  condition_note text not null default 'Baik',
  is_active boolean not null default true,
  created_at timestamptz not null default now(),
  constraint available_not_more_than_total check(available_stock <= total_stock)
);

create table if not exists public.borrow_requests (
  id uuid primary key default gen_random_uuid(),
  request_code text unique not null default upper(substr(replace(gen_random_uuid()::text,'-',''),1,10)),
  student_name text not null check(length(trim(student_name)) between 2 and 100),
  class_name text not null references public.school_classes(name),
  purpose text,
  borrow_date date not null,
  expected_return_date date not null,
  actual_return_date date,
  status public.borrow_status not null default 'pending',
  admin_note text,
  created_at timestamptz not null default now(),
  created_by uuid references auth.users(id),
  check(expected_return_date >= borrow_date)
);

create table if not exists public.borrow_request_items (
  id uuid primary key default gen_random_uuid(),
  request_id uuid not null references public.borrow_requests(id) on delete cascade,
  equipment_id uuid not null references public.equipment(id),
  quantity integer not null check(quantity > 0),
  unique(request_id,equipment_id)
);

create table if not exists public.admin_profiles (
  user_id uuid primary key references auth.users(id) on delete cascade,
  display_name text not null,
  role text not null default 'admin' check(role in ('admin'))
);

create table if not exists public.inventory_movements (
  id bigint generated by default as identity primary key,
  equipment_id uuid not null references public.equipment(id),
  request_id uuid references public.borrow_requests(id),
  movement_type text not null check(movement_type in ('borrow','return','stock_adjustment')),
  quantity integer not null,
  note text,
  actor uuid references auth.users(id),
  created_at timestamptz not null default now()
);

create index if not exists idx_requests_status_date on public.borrow_requests(status,borrow_date,expected_return_date);
create index if not exists idx_request_items_request on public.borrow_request_items(request_id);

create or replace function public.is_admin()
returns boolean language sql stable security definer set search_path=public
as $$ select exists(select 1 from public.admin_profiles where user_id=auth.uid() and role='admin') $$;

